"""Golden renders of helm/charts/karpenter-pools, one per AWS case of the sizing matrix.

Each case resolves the dial test_resolve_sizing.py snapshots in
`fixtures/sizing/golden-matrix.json`, renders the chart with `helm template` from
the resolver's values overlay over the cluster facts a deploy supplies, and holds
the output byte for byte to `fixtures/node-pools/<case>.yaml`. On-prem cases
resolve no pool, so only the AWS ones render. Two things no cluster receives are
dropped first: Helm's `# Source:` lines, which name the template file, and blank
lines between documents, which Helm 4.3 writes and Helm 4.1 does not.

One more case, RUN_CASE, renders what no sizing case reaches: a maintenance
window's scheduled budget, a test run's tags and node script, and the pool fields
only a deployer's own overlay sets. Each sizing case is also rendered the way Argo
deploys it, from the resolver's JSON on the cluster secret through
layer2-platform.yaml's values block, and held to the same golden.

    python3 -m pytest scripts/tests/test_node_pools_golden.py -q

REGENERATING THE GOLDENS IS A DELIBERATE ACT, never a way past a red test. Read
the failing diff first and satisfy yourself every moved line is one you meant to
move, then:

    NODE_POOLS_GOLDEN=write python3 -m pytest scripts/tests/test_node_pools_golden.py

and commit the goldens in the SAME commit as the change that moved them, so the
review sees the cause and the effect together.

Needs `helm` on PATH.
"""

import base64
import difflib
import json
import os
import re
from pathlib import Path

import pytest
from test_karpenter_pools import appset_values, helm
from test_resolve_sizing import (
    CHART_RENDER_BASES,
    CHARTS_DIR,
    HELM_BIN,
    _dial,
    _helm_template,
    _matrix_cases,
    _run,
    _with_disruption,
)

GOLDENS = Path(__file__).resolve().parent / "fixtures" / "node-pools"
CHART = "karpenter-pools"
WRITE_GOLDEN = os.environ.get("NODE_POOLS_GOLDEN") == "write"
REWRITE = "NODE_POOLS_GOLDEN=write python3 -m pytest scripts/tests/test_node_pools_golden.py"
HEADER = (
    "# Generated by scripts/tests/test_node_pools_golden.py from the live render of\n"
    "# {case}. Do not edit: rewrite it.\n"
)
SOURCE_LINE = re.compile(r"^# Source: .*\n", re.M)
# A document separator sits at column 0, so no block scalar's own blank line is caught.
BLANK_BEFORE_SEPARATOR = re.compile(r"\n\n+(?=---\n)")

SIZING_CASES = {name: dial for name, dial in _matrix_cases().items() if dial["cloud"] == "aws"}

RUN_CASE = "aws-scale-economy-10000-test-run"
RUN_DIAL = SIZING_CASES["aws-scale-economy-10000"]
RUN_WINDOW = '    maintenance_window:\n      schedule: "30 22 * * 6"\n      duration: "3h30m"\n'
RUN_NODE_SCRIPT = "#!/bin/bash\nset -euo pipefail\necho mirrors\n"
# Applied after the resolver's overlay: a test run's cluster facts, then one pool
# carrying every field no resolve writes, generationIn dropped for its floor.
RUN_OVERLAY: dict[str, object] = {
    "pools": {
        "aws": {
            "cluster": {"userData": base64.b64encode(RUN_NODE_SCRIPT.encode()).decode()},
            "tags": {"dfe-e2e": "run-1", "expires-at": "2026-10-08T12:00:00Z"},
        },
        "classes": {
            "general": {
                "weight": 10,
                "minVcpu": 4,
                "minMemoryGib": 16,
                "terminationGracePeriod": "2h",
                "aws": {
                    "generationIn": None,
                    "generationGt": "7",
                    "nodeClass": {"metadata": {"httpPutResponseHopLimit": 2}},
                },
            }
        },
    }
}

CASES = sorted([*SIZING_CASES, RUN_CASE])


def normalise(case: str, rendered: str) -> str:
    """`helm template` output as a golden file holds it."""
    body = BLANK_BEFORE_SEPARATOR.sub("\n", SOURCE_LINE.sub("", rendered))
    return HEADER.format(case=case) + body


def render(out: Path, case: str) -> str:
    """One case resolved into `out` and rendered, as its golden file holds it."""
    if case == RUN_CASE:
        assert _run(_with_disruption(_dial(out, **RUN_DIAL), RUN_WINDOW), out, cloud="aws") == 0
        overlay = RUN_OVERLAY
    else:
        dial = SIZING_CASES[case]
        _run(_dial(out, **dial), out, cloud=dial["cloud"])
        overlay = None
    fragment = out / "sizing" / "scale.values.yaml"
    result = _helm_template(CHART, CHART_RENDER_BASES[CHART], fragment, overlay)
    assert result.returncode == 0, result.stderr
    return normalise(case, result.stdout)


@pytest.mark.parametrize("case", CASES)
def test_each_golden_is_the_live_render(tmp_path: Path, case: str) -> None:
    if HELM_BIN is None:
        pytest.skip("helm is not on PATH")
    live = render(tmp_path, case)
    path = GOLDENS / f"{case}.yaml"
    if WRITE_GOLDEN:
        GOLDENS.mkdir(parents=True, exist_ok=True)
        path.write_text(live, encoding="utf-8", newline="\n")
        pytest.skip("golden rewritten -- review the diff before committing it")
    assert path.is_file(), f"{path} is missing: run {REWRITE}"
    committed = path.read_text(encoding="utf-8")
    moved = "".join(
        difflib.unified_diff(
            committed.splitlines(keepends=True), live.splitlines(keepends=True), "golden", "live"
        )
    )
    assert committed == live, f"{case} moved -- if every line is meant, run {REWRITE}\n{moved}"


@pytest.mark.parametrize("case", sorted(SIZING_CASES))
def test_the_appset_path_renders_each_golden(tmp_path: Path, case: str) -> None:
    """What Argo deploys: the resolver's JSON and the cluster facts on the cluster
    secret, through layer2-platform.yaml's values block, render the same bytes."""
    if HELM_BIN is None:
        pytest.skip("helm is not on PATH")
    dial = SIZING_CASES[case]
    _run(_dial(tmp_path, **dial), tmp_path, cloud=dial["cloud"])
    cluster = CHART_RENDER_BASES[CHART]["pools"]["aws"]["cluster"]
    resolved = (tmp_path / "sizing" / "scale.karpenter.json").read_text(encoding="utf-8").strip()
    values = appset_values(
        {
            "dfe.hyperi.io/karpenter_discovery_tag": cluster["discoveryTag"],
            "dfe.hyperi.io/karpenter_instance_profile": cluster["instanceProfile"],
            "dfe.hyperi.io/karpenter_kms_key_id": cluster["kmsKeyId"],
            "dfe.hyperi.io/karpenter_pools": resolved,
        }
    )
    path = tmp_path / "appset-values.json"
    path.write_text(json.dumps(values), encoding="utf-8")
    result = helm(["helm", "template", "t", str(CHARTS_DIR / CHART), "-f", str(path)])
    assert result.returncode == 0, result.stderr
    golden = (GOLDENS / f"{case}.yaml").read_text(encoding="utf-8")
    assert normalise(case, result.stdout) == golden


def test_no_golden_is_left_without_its_case() -> None:
    """A golden for a case the matrix dropped is a frozen render nothing checks."""
    stale = sorted(set(GOLDENS.glob("*.yaml")) - {GOLDENS / f"{case}.yaml" for case in CASES})
    if WRITE_GOLDEN:
        for path in stale:
            path.unlink()
        pytest.skip(f"removed {len(stale)} stale golden(s)")
    assert stale == []


def test_source_lines_and_document_spacing_move_no_golden() -> None:
    """Helm 4.3 output, rebuilt from a golden: a `# Source:` line and a blank line at each document."""
    case = min(CASES)
    golden = (GOLDENS / f"{case}.yaml").read_text(encoding="utf-8")
    body = golden.removeprefix(HEADER.format(case=case))
    sourced = re.sub(r"^---\n", "---\n# Source: karpenter-pools/templates/karpenter/nodepool.yaml\n", body, flags=re.M)
    spaced = sourced.replace("\n---\n", "\n\n---\n")
    assert spaced.count("\n\n---\n") > 1, "the rebuilt render spaced no document"
    assert normalise(case, spaced) == golden


def test_the_same_case_renders_the_same_bytes_twice(tmp_path: Path) -> None:
    """A golden is only a baseline if the render is deterministic, output directory included."""
    if HELM_BIN is None:
        pytest.skip("helm is not on PATH")
    case = min(CASES)
    first, second = tmp_path / "first", tmp_path / "second"
    first.mkdir()
    second.mkdir()
    assert render(first, case) == render(second, case)
