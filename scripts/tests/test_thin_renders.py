"""The golden renders under fixtures/thin-renders, one per cell of _gate.CELLS.

    python3 -m pytest scripts/tests/test_thin_renders.py -q
    python3 scripts/tests/test_thin_renders.py --write

Each golden is what Argo deploys for one component on one profile and cloud, or
one scenario: the thin chart assembled from its committed contract beside
dfe-extras, with the integration values under argocd/values/apps. A change to a
values file, an appset, dfe-extras or a contract moves the live render, and the
first test fails naming each cell and leaf that moved.

REWRITING THE GOLDENS IS A DELIBERATE ACT, never a way past a red test. Read the
failing diff, satisfy yourself every moved leaf is one you meant to move, then run
the --write line above and commit the goldens in the SAME commit as the change
that moved them, so the review reads the cause and the effect together. A release
that only moves an image pin moves no golden: each pin is held as a token.

The renders need helm and the scalo-service library (_weave.library).
"""

import argparse
import sys

import pytest
import yaml

from _gate import (
    CELLS,
    GOLDENS,
    PIN_TOKEN_RE,
    cell,
    golden,
    golden_path,
    golden_text,
    mask,
    pins,
    render_differences,
    unmask,
)
from _weave import REPO_ROOT, render_app

REWRITE = "python3 scripts/tests/test_thin_renders.py --write"
HEADER = (
    "# Generated by scripts/tests/test_thin_renders.py --write from the live render of\n"
    "# {cell}. Do not edit: rewrite it.\n"
)


def _label(service: str, profile: str, cloud: str, scenario: str) -> str:
    return f"{service} {profile}/{cloud} ({scenario})"


def expected_text(service: str, profile: str, cloud: str, scenario: str) -> str:
    """The golden file a cell's live render writes."""
    label = _label(service, profile, cloud, scenario)
    return HEADER.format(cell=label) + golden_text(cell(service, profile, cloud, scenario))


@pytest.mark.parametrize(("service", "profile", "cloud", "scenario"), CELLS)
def test_each_golden_is_the_live_render(
    service: str, profile: str, cloud: str, scenario: str
) -> None:
    path = golden_path(service, profile, cloud, scenario)
    assert path.is_file(), f"{path} is missing: run {REWRITE}"
    committed = [d for d in yaml.safe_load_all(unmask(path.read_text(encoding="utf-8"))) if d]
    live = cell(service, profile, cloud, scenario)
    assert render_differences(committed, live) == []
    assert path.read_text(encoding="utf-8") == expected_text(service, profile, cloud, scenario)


def test_no_golden_is_left_without_its_cell() -> None:
    wanted = {golden_path(*c) for c in CELLS}
    assert sorted(set(GOLDENS.rglob("*.yaml")) - wanted) == []


def test_every_token_names_a_pin_the_stack_carries() -> None:
    found = set()
    for path in GOLDENS.rglob("*.yaml"):
        found |= {m.group(1) for m in PIN_TOKEN_RE.finditer(path.read_text(encoding="utf-8"))}
    assert sorted(found - set(pins())) == []


def test_a_moved_leaf_fails_the_check() -> None:
    """A deployer-visible change the goldens do not hold is named leaf by leaf."""
    moved = render_app("dfe-ui", "slim", "local", overlay={"fullnameOverride": "dfe-ui-renamed"})
    found = render_differences(golden("dfe-ui", "slim", "local"), moved)
    assert "only left: Deployment/dfe-ui" in found, found
    assert "only right: Deployment/dfe-ui-renamed" in found, found


# ---------------------------------------------------------------- the pin tokens


def _key_of(value: str) -> str:
    """The token a pin's value takes: the first key, in order, that carries it."""
    return min(k for k, v in pins().items() if v == value)


def test_a_pin_is_tokenised_wherever_it_stands_alone() -> None:
    value = pins()["digests.dfe-receiver"]
    text = f"image: registry.example.com/x:v1@{value}\n"
    assert mask(text) == f"image: registry.example.com/x:v1@<pin:{_key_of(value)}>\n"
    assert unmask(mask(text)) == text


def test_a_chart_label_carries_the_chart_version_token() -> None:
    chart = pins()["chart-version.dfe-receiver"]
    text = f"helm.sh/chart: dfe-receiver-{chart}\n"
    assert mask(text) == f"helm.sh/chart: dfe-receiver-<pin:{_key_of(chart)}>\n"
    assert unmask(mask(text)) == text


def test_a_value_inside_a_longer_version_is_left_alone() -> None:
    value = pins()["apps.dfe-receiver"]
    assert mask(f"tag: {value}.9\n") == f"tag: {value}.9\n"
    assert mask(f"tag: 1{value.removeprefix('v')}\n") == f"tag: 1{value.removeprefix('v')}\n"
    assert mask(f"tag: {value}\n") == f"tag: <pin:{_key_of(value)}>\n"


def test_a_token_naming_no_pin_fails_the_read() -> None:
    with pytest.raises(KeyError):
        unmask("tag: <pin:apps.no-such-app>\n")


# ---------------------------------------------------------------- the rewrite


def write() -> int:
    """Rewrite every golden from the live render; prints each file that moved."""
    moved = 0
    GOLDENS.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for service, profile, cloud, scenario in CELLS:
        path = golden_path(service, profile, cloud, scenario)
        wanted.add(path)
        text = expected_text(service, profile, cloud, scenario)
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
        moved += 1
    for stale in sorted(set(GOLDENS.rglob("*.yaml")) - wanted):
        stale.unlink()
        print(f"removed {stale.relative_to(REPO_ROOT)}")
        moved += 1
    print(f"{moved} golden file(s) moved")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Check the goldens under pytest, or rewrite them with --write."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--write", action="store_true", help="rewrite the goldens from the live render"
    )
    args = parser.parse_args(argv)
    if args.write:
        return write()
    return pytest.main([__file__, "-q", "-p", "no:cacheprovider"])


if __name__ == "__main__":
    sys.exit(main())
